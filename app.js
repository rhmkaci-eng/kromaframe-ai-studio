let currentLang = localStorage.getItem("kf_lang") || "en";
let currentFilter = "all";

function renderPortfolio() {
  const grid = document.getElementById("portfolioGrid");
  const list = currentFilter === "all" ? PROJECTS : PROJECTS.filter(p => p.cat === currentFilter);
  grid.innerHTML = list.map(p => `
    <article class="work-card" data-id="${p.id}">
      <div class="work-media">
        <img src="${p.poster}" alt="${p.title[currentLang]}" loading="lazy" />
        <video src="${p.video}" muted loop playsinline preload="none"></video>
        <span class="play-pill">▶ 10s • -14 LUFS</span>
      </div>
      <div class="work-body">
        <span class="work-meta">${p.catLabel[currentLang]}</span>
        <h3>${p.title[currentLang]}</h3>
        <p>${p.desc[currentLang]}</p>
      </div>
    </article>
  `).join("");

  grid.querySelectorAll(".work-card").forEach(card => {
    const vid = card.querySelector("video");
    card.addEventListener("mouseenter", () => vid && vid.play().catch(() => {}));
    card.addEventListener("mouseleave", () => { if (vid) { vid.pause(); vid.currentTime = 0; } });
    card.addEventListener("click", () => openModal(card.dataset.id));
  });
}

function renderFaq() {
  const list = document.getElementById("faqList");
  list.innerHTML = FAQS.map((item, idx) => `
    <div class="faq-item ${idx === 0 ? "open" : ""}">
      <button type="button" class="faq-q">
        <span>${item.q[currentLang]}</span>
        <span>${idx === 0 ? "−" : "+"}</span>
      </button>
      <div class="faq-a">${item.a[currentLang]}</div>
    </div>
  `).join("");

  list.querySelectorAll(".faq-q").forEach(btn => {
    btn.addEventListener("click", () => {
      const parent = btn.parentElement;
      const isOpen = parent.classList.toggle("open");
      btn.lastElementChild.textContent = isOpen ? "−" : "+";
    });
  });
}

function applyLang(lang) {
  currentLang = I18N[lang] ? lang : "en";
  localStorage.setItem("kf_lang", currentLang);
  document.documentElement.lang = currentLang;
  document.documentElement.dir = currentLang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll(".lang-btn").forEach(b => b.classList.toggle("active", b.dataset.lang === currentLang));
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (I18N[currentLang][key]) el.textContent = I18N[currentLang][key];
  });

  renderPortfolio();
  renderFaq();
}

const modal = document.getElementById("videoModal");
const modalVideo = document.getElementById("modalVideo");

function openModal(id) {
  const p = PROJECTS.find(x => x.id === id);
  if (!p) return;
  document.getElementById("modalCat").textContent = p.catLabel[currentLang];
  document.getElementById("modalTitle").textContent = p.title[currentLang];
  document.getElementById("modalDesc").textContent = p.desc[currentLang];
  modalVideo.src = p.video;
  modalVideo.poster = p.poster;
  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");
  modalVideo.play().catch(() => {});
}

function closeModal() {
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
  modalVideo.pause();
  modalVideo.removeAttribute("src");
}

document.getElementById("modalClose").addEventListener("click", closeModal);
document.getElementById("modalBackdrop").addEventListener("click", closeModal);
document.addEventListener("keydown", e => { if (e.key === "Escape") closeModal(); });

document.querySelectorAll(".lang-btn").forEach(btn => {
  btn.addEventListener("click", () => applyLang(btn.dataset.lang));
});

